"""Validated, durable contracts exchanged between pipeline stages."""

from __future__ import annotations

from datetime import datetime

from pydantic import AliasChoices, BaseModel, ConfigDict, Field


class PipelineRun(BaseModel):
    """Identifies one reproducible training run."""

    model_config = ConfigDict(frozen=True)

    training_run_id: str = Field(
        min_length=1,
        validation_alias=AliasChoices("training_run_id", "run_id"),
    )
    start_date: datetime
    end_date: datetime


class PreprocessedSnapshot(BaseModel):
    """Locations and metadata for a materialized preprocessing result."""

    model_config = ConfigDict(frozen=True)

    training_run_id: str = Field(
        min_length=1,
        validation_alias=AliasChoices("training_run_id", "run_id"),
    )
    log_uri: str = Field(min_length=1)
    user_uri: str = Field(min_length=1)
    content_uri: str = Field(min_length=1)
    row_count: int = Field(ge=0)
    schema_version: str = "v1"


class FeatureSnapshot(BaseModel):
    """Locations and metadata for a materialized feature set."""

    model_config = ConfigDict(frozen=True)

    training_run_id: str = Field(
        min_length=1,
        validation_alias=AliasChoices("training_run_id", "run_id"),
    )
    log_uri: str = Field(min_length=1)
    concept_matrix_uri: str = Field(min_length=1)
    level4_matrix_uri: str = Field(min_length=1)
    row_count: int = Field(ge=0)
    schema_version: str = "v1"


class ModelRegistration(BaseModel):
    """Metadata for the approved model generated by a training run."""

    model_config = ConfigDict(frozen=True)

    training_run_id: str = Field(
        min_length=1,
        validation_alias=AliasChoices("training_run_id", "run_id"),
    )
    model_version: str = Field(min_length=1)
    model_uri: str = Field(min_length=1)
    scaler_uri: str = Field(min_length=1)
    metrics_uri: str = Field(min_length=1)
    manifest_uri: str
    model_type: str = Field(min_length=1)
    test_score: float
