"""Small, durable contracts exchanged between pipeline stages."""

from __future__ import annotations

from dataclasses import asdict, dataclass
from datetime import datetime


@dataclass(frozen=True)
class PipelineRun:
    """Identifies one reproducible training run."""

    run_id: str
    start_date: datetime
    end_date: datetime


@dataclass(frozen=True)
class FeatureSnapshot:
    """Locations and metadata for a materialized feature set."""

    run_id: str
    log_uri: str
    concept_matrix_uri: str
    level4_matrix_uri: str
    row_count: int
    schema_version: str = "v1"

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass(frozen=True)
class ModelRegistration:
    """Metadata for the approved model generated by a training run."""

    run_id: str
    model_version: str
    model_uri: str
    scaler_uri: str
    metrics_uri: str
    manifest_uri: str
    model_type: str
    test_score: float

    def to_dict(self) -> dict:
        return asdict(self)
